/**
 * Filter areas belonging to a specific view ('chat' | 'chatlist' | 'dialogs')
 */
export function getAreasForView(view: InspectorView): InspectorArea[] {
  if (view === 'all') {
    return INSPECTOR_AREAS;
  }
  return INSPECTOR_AREAS.filter(area => area.view === view);
}

/**
 * Find the primary area for a given variable key.
 * If preferView is supplied, it chooses an area matching that view if variable belongs to multiple.
 */
export function findAreaForVariable(
  key: string,
  preferView?: 'chat' | 'chatlist' | 'dialogs'
): InspectorArea | undefined {
  const matches = INSPECTOR_AREAS.filter(a => a.keys.includes(key));
  if (matches.length === 0) return undefined;
  if (preferView) {
    const preferred = matches.find(a => a.view === preferView);
    if (preferred) return preferred;
  }
  return matches[0];
}

/**
 * Find the primary view for a given variable key.
 */
export function findViewForVariable(
  key: string,
  preferView?: 'chat' | 'chatlist' | 'dialogs'
): 'chat' | 'chatlist' | 'dialogs' {
  const area = findAreaForVariable(key, preferView);
  return area?.view || 'chat';
}

